function saveEnv(values: Map<string, string>): void {
  fs.mkdirSync(CONFIG_DIR, {
    recursive: true,
    mode: 0o700,
  });

  const temp = `${ENV_FILE}.tmp-${process.pid}`;

  fs.writeFileSync(temp, renderEnv(values), {
    encoding: 'utf8',
    mode: 0o600,
  });

  fs.renameSync(temp, ENV_FILE);

  fs.chmodSync(CONFIG_DIR, 0o700);
  fs.chmodSync(ENV_FILE, 0o600);
}

function setIfEntered(
  values: Map<string, string>,
  key: string,
  value: string,
  fallback?: string
): void {
  const normalized = value.trim();

  if (normalized) {
    values.set(key, normalized);
    return;
  }

  if (!values.get(key) && fallback !== undefined) {
    values.set(key, fallback);
  }
}

async function secretQuestion(rl: readline.Interface, label: string): Promise<string> {
  if (!input.isTTY) {
    return '';
  }

  rl.pause();

  output.write(label);

  return new Promise((resolve) => {
    let value = '';
    let finished = false;

    const finish = () => {
      if (finished) {
        return;
      }

      finished = true;

      input.off('data', onData);
      input.setRawMode?.(false);
      input.pause();

      output.write('\n');

      rl.resume();

      resolve(value);
    };

    const onData = (chunk: Buffer) => {
      for (const ch of chunk.toString('utf8')) {
        if (ch === '\r' || ch === '\n') {
          finish();
          return;
        }

        if (ch === '\u0003') {
          input.off('data', onData);
          input.setRawMode?.(false);
          output.write('\n');
          process.exit(130);
        }

        if (ch === '\u007f') {
          value = value.slice(0, -1);
          continue;
        }

        value += ch;
      }
    };

    input.resume();
    input.setRawMode?.(true);
    input.on('data', onData);
  });
}

