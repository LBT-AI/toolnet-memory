async function configureR2(rl: readline.Interface, values: Map<string, string>): Promise<void> {
  console.log('');
  console.log('Cloudflare R2');
  console.log('──────────────────────────────────────');

  const accountId = await rl.question(
    values.get('R2_ACCOUNT_ID') ? `ACCOUNT ID [${values.get('R2_ACCOUNT_ID')}]: ` : 'ACCOUNT ID: '
  );

  const access = await rl.question(
    values.get('R2_ACCESS_KEY_ID')
      ? `ACCESS KEY ID [${masked(values.get('R2_ACCESS_KEY_ID'))}]: `
      : 'ACCESS KEY ID: '
  );

  const bucket = await rl.question(`BUCKET [${values.get('R2_BUCKET') || 'toolnet-memory'}]: `);

  setIfEntered(values, 'R2_ACCOUNT_ID', accountId);
  setIfEntered(values, 'R2_ACCESS_KEY_ID', access);
  setIfEntered(values, 'R2_BUCKET', bucket, 'toolnet-memory');

  const secret = await secretQuestion(
    rl,
    values.get('R2_SECRET_ACCESS_KEY')
      ? 'SECRET ACCESS KEY [configured, Enter = keep]: '
      : 'SECRET ACCESS KEY: '
  );

  if (secret.trim()) {
    values.set('R2_SECRET_ACCESS_KEY', secret.trim());
  }
}

