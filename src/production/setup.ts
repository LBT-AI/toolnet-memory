function parseEnv(text: string): Map<string, string> {
  const values = new Map<string, string>();

  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();

    if (!line || line.startsWith('#')) {
      continue;
    }

    const index = line.indexOf('=');

    if (index === -1) {
      continue;
    }

    const key = line.slice(0, index).trim();
    const value = line.slice(index + 1).trim();

    if (key) {
      values.set(key, value);
    }
  }

  return values;
}

function providerFrom(values: Map<string, string>): StorageProviderName {
  const explicit = values.get('MEMORY_STORAGE_PROVIDER')?.trim();

  if (
    explicit === 'r2' ||
    explicit === 's3' ||
    explicit === 'local' ||
    explicit === 'huggingface'
  ) {
    return explicit;
  }

  if (values.get('R2_ACCOUNT_ID') && values.get('R2_BUCKET')) {
    return 'r2';
  }

  if (values.get('S3_BUCKET')) {
    return 's3';
  }

  if (values.get('HF_BUCKET') && values.get('HF_S3_ACCESS_KEY_ID')) {
    return 'huggingface';
  }

  if (values.get('MEMORY_LOCAL_STORAGE_PATH')) {
    return 'local';
  }

  return 'r2';
}

function providerLabel(provider: StorageProviderName): string {
  switch (provider) {
    case 'r2':
      return 'Cloudflare R2';

    case 's3':
      return 'S3 / S3-compatible';

    case 'huggingface':
      return 'Hugging Face S3';

    case 'local':
      return 'Local';

    default:
      return provider;
  }
}

function requiredFor(provider: StorageProviderName): string[] {
  switch (provider) {
    case 'r2':
      return ['R2_ACCOUNT_ID', 'R2_BUCKET', 'R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY'];

    case 's3':
      return ['S3_BUCKET', 'S3_ACCESS_KEY_ID', 'S3_SECRET_ACCESS_KEY'];

    case 'huggingface':
      return ['HF_BUCKET', 'HF_S3_ACCESS_KEY_ID', 'HF_S3_SECRET_ACCESS_KEY'];

    case 'local':
      return [];

    default:
      return [];
  }
}

function storageConfigured(values: Map<string, string>): boolean {
  const provider = providerFrom(values);

  if (provider === 'local') {
    return true;
  }

  return requiredFor(provider).every((key) => Boolean(values.get(key)?.trim()));
}

function masked(value: string | undefined): string {
  if (!value) {
    return 'not configured';
  }

  if (value.length <= 8) {
    return 'configured';
  }

  return `${value.slice(0, 4)}••••${value.slice(-3)}`;
}

