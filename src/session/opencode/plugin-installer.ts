import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

import { homedir } from 'node:os';

import { dirname, join, parse, resolve } from 'node:path';

const START = '<!-- TOOLNET_MEMORY_BOOTSTRAP_START -->';

const END = '<!-- TOOLNET_MEMORY_BOOTSTRAP_END -->';

function installBootstrapInstructions() {
  const file = join(homedir(), '.config', 'opencode', 'AGENTS.md');

  mkdirSync(join(homedir(), '.config', 'opencode'), {
    recursive: true,
  });

  const block = `${START}
## ToolNet Memory

ToolNet Memory is available for projects that already contain a valid \`.toolnet/project.json\`.

Rules:

1. Do not create a ToolNet project automatically.
2. If no valid \`.toolnet/project.json\` exists in the current project or an ancestor, ignore ToolNet Memory.
3. Normal startup context must stay small and selective.
4. Do not automatically run deep recovery commands.
5. Use ToolNet MCP or selective retrieval when older project knowledge is actually needed.
6. Raw transcripts must not be injected into prompts.
7. Current repository evidence has priority over stale memory when they conflict.

${END}`;

  let content = existsSync(file) ? readFileSync(file, 'utf8') : '';

  const start = content.indexOf(START);

  const end = content.indexOf(END);

  if (start >= 0 && end >= start) {
    content = content.slice(0, start) + block + content.slice(end + END.length);
  } else {
    content = content.trimEnd();

    if (content) {
      content += '\n\n';
    }

    content += block;
  }

  writeFileSync(file, content.trimEnd() + '\n', {
    encoding: 'utf8',
    mode: 0o600,
  });

  return file;
}

export function installOpenCodePlugin(
  options: {
    directory?: string;
    binary?: string;
  } = {}
): string {
  const directory = options.directory ?? join(homedir(), '.config', 'opencode', 'plugins');

  mkdirSync(directory, {
    recursive: true,
  });

  installBootstrapInstructions();

  const target = join(directory, 'toolnet-memory.js');

  const binary = options.binary ?? process.env.TOOLNET_MEMORY_BIN ?? 'toolnet-memory';

  const content = `
// Generated by ToolNet Memory.
// OpenCode integration:
// - project gated
// - selective context injection
// - incremental session checkpoints
// - periodic durability sync
// - best-effort shutdown flush

import fs from "node:fs"
import path from "node:path"
import os from "node:os"

const TOOLNET_BINARY =
  ${JSON.stringify(binary)}

const CONTEXT_MAX_TOKENS = 700

const CONTEXT_CACHE_MS = 5000

const PERIODIC_SYNC_MS = 30000

const SYNC_TIMEOUT_MS = 15000

const STATUS_FILE = path.join(
  os.homedir(),
  ".config",
  "toolnet-memory",
  "opencode-sync-status.json"
)

function writeStatus(data) {
  try {
    fs.mkdirSync(
      path.dirname(
        STATUS_FILE
      ),
      {
        recursive: true,
      }
    )

    fs.writeFileSync(
      STATUS_FILE,
      JSON.stringify(
        {
          timestamp:
            new Date()
              .toISOString(),
          ...data,
        },
        null,
        2
      ) + "\\n"
    )
  } catch {
    // Status reporting must
    // never break OpenCode.
  }
}

function validProjectManifest(
  file
) {
  try {
    const parsed =
      JSON.parse(
        fs.readFileSync(
          file,
          "utf8"
        )
      )

    return Boolean(
      parsed &&
      typeof parsed ===
        "object" &&
      typeof parsed.id ===
        "string" &&
      parsed.id.length > 0
    )
  } catch {
    return false
  }
}

function findProjectRoot(
  inputDirectory
) {
  let current =
    path.resolve(
      inputDirectory
    )

  const filesystemRoot =
    path.parse(
      current
    ).root

  while (true) {
    const manifest =
      path.join(
        current,
        ".toolnet",
        "project.json"
      )

    if (
      fs.existsSync(
        manifest
      ) &&
      validProjectManifest(
        manifest
      )
    ) {
      return current
    }

    if (
      current ===
      filesystemRoot
    ) {
      break
    }

    const parent =
      path.dirname(
        current
      )

    if (
      parent === current
    ) {
      break
    }

    current = parent
  }

  return null
}

function getSessionId(
  event
) {
  const p =
    event?.properties ?? {}

  const candidates = [
    p.sessionID,
    p.sessionId,
    p.info?.id,
    p.session?.id,
  ]

  return (
    candidates.find(
      value =>
        typeof value ===
          "string" &&
        value.length > 0
    ) ?? null
  )
}

async function runWithTimeout(
  args,
  {
    stdout = "ignore",
    timeout =
      SYNC_TIMEOUT_MS,
  } = {}
) {
  const child =
    Bun.spawn(
      args,
      {
        stdin:
          "ignore",
        stdout,
        stderr:
          "ignore",
      }
    )

  let timer

  const timeoutPromise =
    new Promise(
      (_, reject) => {
        timer =
          setTimeout(
            () => {
              try {
                child.kill()
              } catch {}

              reject(
                new Error(
                  "ToolNet command timeout"
                )
              )
            },
            timeout
          )
      }
    )

  try {
    const exitCode =
      await Promise.race([
        child.exited,
        timeoutPromise,
      ])

    if (
      typeof exitCode ===
        "number" &&
      exitCode !== 0
    ) {
      throw new Error(
        \`ToolNet exited with code \${exitCode}\`
      )
    }

    return child
  } finally {
    if (timer) {
      clearTimeout(
        timer
      )
    }
  }
}

export const ToolNetMemoryPlugin =
  async ({
    directory,
  }) => {
    /*
     * CRITICAL:
     * Never auto-create a ToolNet
     * project just because OpenCode
     * happens to start in /root,
     * /tmp, $HOME, etc.
     */
    const projectRoot =
      findProjectRoot(
        directory
      )

    if (!projectRoot) {
      writeStatus({
        active: false,
        reason:
          "no-toolnet-project",
        directory,
      })

      return {}
    }

    writeStatus({
      active: true,
      projectRoot,
      state:
        "plugin-loaded",
    })

    let lastSessionId =
      null

    let syncChain =
      Promise.resolve()

    let contextCache = {
      value: "",
      expiresAt: 0,
    }

    async function readContext() {
      const now =
        Date.now()

      if (
        contextCache.value &&
        now <
          contextCache.expiresAt
      ) {
        return (
          contextCache.value
        )
      }

      try {
        const child =
          Bun.spawn(
            [
              TOOLNET_BINARY,
              "context:print",
              "--project",
              projectRoot,
              "--tokens",
              String(
                CONTEXT_MAX_TOKENS
              ),
            ],
            {
              stdin:
                "ignore",
              stdout:
                "pipe",
              stderr:
                "ignore",
            }
          )

        const textPromise =
          new Response(
            child.stdout
          ).text()

        const exitCode =
          await child.exited

        if (
          exitCode !== 0
        ) {
          return ""
        }

        const text =
          (
            await textPromise
          ).trim()

        contextCache = {
          value: text,
          expiresAt:
            now +
            CONTEXT_CACHE_MS,
        }

        return text
      } catch {
        return ""
      }
    }

    async function syncNow(
      sessionId,
      flag,
      reason
    ) {
      if (!sessionId) {
        return
      }

      const args = [
        TOOLNET_BINARY,
        "session:opencode-sync",
        sessionId,
        "--project",
        projectRoot,
      ]

      if (flag) {
        args.push(
          flag
        )
      }

      try {
        await runWithTimeout(
          args
        )

        writeStatus({
          active: true,
          projectRoot,
          sessionId,
          reason,
          state:
            "sync-success",
        })
      } catch (error) {
        writeStatus({
          active: true,
          projectRoot,
          sessionId,
          reason,
          state:
            "sync-failed",
          error:
            error instanceof
            Error
              ? error.message
              : String(
                  error
                ),
        })

        throw error
      }
    }

    function queueSync(
      sessionId,
      flag,
      reason
    ) {
      if (!sessionId) {
        return syncChain
      }

      lastSessionId =
        sessionId

      syncChain =
        syncChain
          .catch(
            () =>
              undefined
          )
          .then(
            () =>
              syncNow(
                sessionId,
                flag,
                reason
              )
          )

      return syncChain
    }

    /*
     * Periodic durability checkpoint.
     *
     * This is intentionally independent
     * from session.idle/dispose because
     * abrupt SSH/process termination may
     * skip shutdown hooks.
     *
     * unref() prevents the timer itself
     * from keeping OpenCode alive.
     */
    const periodic =
      setInterval(
        () => {
          if (
            lastSessionId
          ) {
            void queueSync(
              lastSessionId,
              null,
              "periodic"
            )
          }
        },
        PERIODIC_SYNC_MS
      )

    if (
      typeof periodic.unref ===
        "function"
    ) {
      periodic.unref()
    }

    return {
      event: async ({
        event,
      }) => {
        const sessionId =
          getSessionId(
            event
          )

        if (sessionId) {
          lastSessionId =
            sessionId
        }

        if (
          event.type ===
          "session.idle"
        ) {
          await queueSync(
            sessionId,
            "--idle",
            "session.idle"
          )

          return
        }

        if (
          event.type ===
          "session.compacted"
        ) {
          await queueSync(
            sessionId,
            "--compacted",
            "session.compacted"
          )

          contextCache = {
            value: "",
            expiresAt: 0,
          }

          return
        }

        if (
          event.type ===
          "session.error"
        ) {
          await queueSync(
            sessionId,
            "--error",
            "session.error"
          )

          return
        }
      },

      /*
       * VERIFIED on OpenCode 1.18.14:
       * this hook fires on real model turns.
       *
       * It remains experimental, therefore
       * AGENTS.md + MCP stay as fallbacks.
       */
      "experimental.chat.system.transform":
        async (
          _input,
          output
        ) => {
          const context =
            await readContext()

          if (!context) {
            return
          }

          if (
            Array.isArray(
              output?.system
            )
          ) {
            output.system.push(
              context
            )

            return
          }

          if (
            typeof output?.system ===
            "string"
          ) {
            output.system =
              output.system
                ? \`\${output.system}\\n\\n\${context}\`
                : context
          }
        },

      /*
       * Optional compaction survival hook.
       * We keep it as a supplementary path,
       * never as the only continuity path.
       */
      "experimental.session.compacting":
        async (
          _input,
          output
        ) => {
          const context =
            await readContext()

          if (
            context &&
            Array.isArray(
              output?.context
            )
          ) {
            output.context.push(
              context
            )
          }
        },

      /*
       * VERIFIED for clean OpenCode exits.
       * Best effort only: kill -9 / crash /
       * machine loss cannot guarantee this.
       */
      dispose: async () => {
        clearInterval(
          periodic
        )

        if (
          lastSessionId
        ) {
          try {
            await queueSync(
              lastSessionId,
              "--idle",
              "dispose"
            )
          } catch {
            // Status already recorded.
          }
        }

        try {
          await syncChain
        } catch {
          // Do not block OpenCode shutdown.
        }
      },
    }
  }
`;

  writeFileSync(target, content.trimStart(), {
    encoding: 'utf8',
    mode: 0o600,
  });

  return target;
}
